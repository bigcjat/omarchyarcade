function drawPixelSprite(ctx, spriteName, cx, cy, pixelSize, angle) {
    var sprite = SPRITES[spriteName];
    if (!sprite) return;
    var ps = pixelSize || 2.0;

    ctx.save();
    ctx.translate(cx, cy);
    if (angle && angle !== 0) {
        ctx.rotate(angle);
    }
    // Center of 16x16 sprite is (8, 8)
    var originX = (spriteName === "fighter_dual") ? -16 * ps : -8 * ps;
    var originY = -8 * ps;

    for (var code in sprite) {
        ctx.fillStyle = COLOR_MAP[code] || "#FFFFFF";
        var rects = sprite[code];
        for (var i = 0; i < rects.length; i++) {
            var r = rects[i];
            ctx.fillRect(originX + r[0] * ps, originY + r[1] * ps, r[2] * ps, r[3] * ps);
        }
    }
    ctx.restore();
}
