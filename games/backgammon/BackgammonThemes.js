function getTheme(id) {
    for (var i = 0; i < themes.length; i++) {
        if (themes[i].id === id) return themes[i];
    }
    return themes[0];
}

function getNextTheme(currId) {
    for (var i = 0; i < themes.length; i++) {
        if (themes[i].id === currId) {
            return themes[(i + 1) % themes.length];
        }
    }
    return themes[0];
}
