function getThemeById(id) {
    if (!id) return null;
    var clean = id.toLowerCase().replace(/[_\s]/g, "-");
    for (var i = 0; i < themes.length; i++) {
        var tid = themes[i].id.toLowerCase();
        if (tid === clean || tid.replace(/-/g, "") === clean.replace(/-/g, "")) {
            return themes[i];
        }
    }
    return null;
}

function getTheme(id) {
    var t = getThemeById(id);
    if (t) {
        return {
            bg: t.background,
            fg: t.foreground,
            accent: t.accent,
            surface: t.color0,
            border: t.color8,
            primary: t.color4,
            muted: t.color7
        };
    }
    return {
        bg: "#0B0E14",
        fg: "#E2E8F0",
        accent: "#00F0FF",
        surface: "#1E293B",
        border: "#334155",
        primary: "#3B82F6",
        muted: "#94A3B8"
    };
}

